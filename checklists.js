export function templateFor(asset) {
  const keys = [asset.detail_jenis, asset.jenis, asset.kategori];
  for (const raw of keys) {
    const s = String(raw || '').toLowerCase().trim();
    if (!s) continue;
    for (const t of TEMPLATES) {
      if (t.r && t.r.test(s)) return t;
    }
  }
  return TEMPLATES[TEMPLATES.length - 1];
}

export function getTemplate(key) {
  return TEMPLATES.find((t) => t.k === key) || null;
}

// Versi ringan untuk dikirim ke browser (tanpa regex).
export function publicTemplates() {
  return TEMPLATES.map((t) => ({ key: t.k, name: t.n, items: t.q }));
}
